/**
 * Handbook builder (v1.2.3 Task 16).
 *
 * The in-app guide is the source of truth; this script concatenates the same
 * Markdown files into `docs/HANDBOOK.md` and `docs/HANDBOOK.id.md` so readers on
 * GitHub get identical content without opening the app. Run it as part of the
 * release checklist (not part of `npm test` — it writes files).
 *
 * `[[settings:x]]` / `[[route:x]]` tokens are rendered as plain names, since a
 * Markdown file on GitHub has no in-app router to call.
 *
 * Run: node scripts/build-handbook.mjs
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const GUIDE = path.join(ROOT, 'src', 'guide');

/** Token labels for the standalone document (no app chrome to link into). */
const SETTINGS_NAMES = {
  providers: 'Settings → AI Providers',
  models: 'Settings → Models',
  behavior: 'Settings → Chat Behavior',
  styles: 'Settings → Styles',
  skills: 'Settings → Skills',
  agentmd: 'Settings → agent.md',
  appearance: 'Settings → Appearance',
  memory: 'Settings → Memory',
  usage: 'Settings → Usage',
  data: 'Settings → Data',
  plugins: 'Settings → Plugins',
  automations: 'Settings → Automations',
  mcp: 'Settings → MCP',
  about: 'Settings → About'
};
const ROUTE_NAMES = {
  chat: 'Chat',
  story: 'Story Bible',
  agent: 'Story Agent',
  flow: 'Story Flow',
  chapters: 'Chapters',
  projects: 'Projects',
  stats: 'Writing Stats',
  settings: 'Settings',
  about: 'About'
};

function parse(raw) {
  const text = raw.replace(/\r\n/g, '\n');
  const m = text.match(/^---\n([\s\S]*?)\n---\n?/);
  const meta = {};
  let body = text;
  if (m) {
    for (const line of m[1].split('\n')) {
      const i = line.indexOf(':');
      if (i > 0) meta[line.slice(0, i).trim()] = line.slice(i + 1).trim();
    }
    body = text.slice(m[0].length).trim();
  }
  return { meta, body };
}

function detokenize(md) {
  return md.replace(/\[\[(settings|route|guide):([a-z0-9-]+)\]\]/gi, (_all, kind, target) => {
    if (kind.toLowerCase() === 'settings') return SETTINGS_NAMES[target] || `Settings → ${target}`;
    if (kind.toLowerCase() === 'route') return ROUTE_NAMES[target] || target;
    return target.replace(/-/g, ' ');
  });
}

function build(lang, title) {
  const dir = path.join(GUIDE, lang);
  const docs = fs.readdirSync(dir)
    .filter((f) => f.endsWith('.md'))
    .map((f) => ({ slug: f.replace(/\.md$/, ''), ...parse(fs.readFileSync(path.join(dir, f), 'utf8')) }))
    .sort((a, b) => Number(a.meta.order || 999) - Number(b.meta.order || 999));

  const toc = docs.map((d) => `- [${d.meta.title}](${d.slug})`).join('\n');
  const body = docs
    .map((d) => detokenize(d.body.replace(/^#\s+/m, '## ')))
    .join('\n\n---\n\n');

  return `# ${title}

> Generated from the in-app guide (\`src/guide/${lang}\`) by \`scripts/build-handbook.mjs\`.
> Do not edit this file by hand — edit the articles and re-run the script.

## Contents

${toc}

---

${body}
`;
}

const out = [
  ['HANDBOOK.md', build('en', 'OpenPlot AI Handbook')],
  ['HANDBOOK.id.md', build('id', 'Panduan OpenPlot AI')]
];
for (const [name, content] of out) {
  const file = path.join(ROOT, 'docs', name);
  fs.writeFileSync(file, content);
  console.log(`wrote docs/${name} (${content.split('\n').length} lines)`);
}
